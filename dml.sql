-- Usuarios com perfil de investidor
SELECT U.ID,
       U.NOME,
       U.EMAIL,
       P.NOME_PERFIL,
       P.NIVEL_RISCO
  FROM USUARIO U
  LEFT JOIN PERFIL_INVESTIDOR P
    ON P.ID = U.ID_PERFIL_INVESTIDOR
 ORDER BY U.ID;

-- Carteiras e suas empresas
SELECT C.ID,
       C.NOME AS CARTEIRA,
       C.SALDO_TOTAL,
       E.NOME AS EMPRESA
  FROM CARTEIRA C
  JOIN EMPRESA E
    ON E.ID = C.ID_EMPRESA
 ORDER BY C.ID;

-- Ativos pertencentes a determinada carteira (exemplo: carteira 1)
SELECT C.NOME AS CARTEIRA,
       A.NOME AS ATIVO,
       CA.QUANTIDADE,
       CA.PRECO_MEDIO,
       A.VALOR_ATUAL,
       (A.VALOR_ATUAL * CA.QUANTIDADE) AS VALOR_ATUAL_POSICAO
  FROM CARTEIRA_ATIVO CA
  JOIN CARTEIRA C ON C.ID = CA.ID_CARTEIRA
  JOIN ATIVO A ON A.ID = CA.ID_ATIVO
 WHERE C.ID = 1
 ORDER BY A.NOME;

-- Empresas vinculadas a determinado usuario (exemplo: usuario 1)
SELECT U.NOME AS USUARIO,
       E.NOME AS EMPRESA,
       UE.CARGO,
       UE.DATA_VINCULO
  FROM USUARIO_EMPRESA UE
  JOIN USUARIO U ON U.ID = UE.ID_USUARIO
  JOIN EMPRESA E ON E.ID = UE.ID_EMPRESA
 WHERE U.ID = 1
 ORDER BY E.NOME;

-- Transacoes com carteira e ativo negociado
SELECT T.ID,
       T.TIPO,
       T.VALOR,
       T.DATA_TRANSACAO,
       C.NOME AS CARTEIRA,
       A.NOME AS ATIVO,
       T.DESCRICAO
  FROM TRANSACAO T
  JOIN CARTEIRA C ON C.ID = T.ID_CARTEIRA
  LEFT JOIN ATIVO A ON A.ID = T.ID_ATIVO
 ORDER BY T.DATA_TRANSACAO;

-- Relatorios solicitados por usuario
SELECT U.NOME AS USUARIO,
       R.TIPO,
       R.DATA_GERACAO,
       R.CONTEUDO
  FROM RELATORIO R
  JOIN USUARIO U ON U.ID = R.ID_USUARIO
 ORDER BY U.NOME, R.DATA_GERACAO;
