-- ============================================================
-- 7. CHECK CONSTRAINTS
-- ============================================================

ALTER TABLE AUTENTICACAO_MULTIFATOR
    ADD CONSTRAINT CK_MFA_CODIGO
    CHECK (CODIGO IS NULL OR LENGTH(CODIGO) = 6);

ALTER TABLE PERFIL_INVESTIDOR
    ADD CONSTRAINT CK_PERFIL_RISCO
    CHECK (NIVEL_RISCO IN ('BAIXO', 'MEDIO', 'ALTO'));

ALTER TABLE CARTEIRA
    ADD CONSTRAINT CK_CART_SALDO
    CHECK (SALDO_TOTAL >= 0);

ALTER TABLE ATIVO
    ADD CONSTRAINT CK_ATIVO_VALOR
    CHECK (VALOR_ATUAL >= 0);

ALTER TABLE ATIVO
    ADD CONSTRAINT CK_ATIVO_QTD
    CHECK (QUANTIDADE >= 0);

ALTER TABLE FUNDO_INVESTIMENTO
    ADD CONSTRAINT CK_FUNDO_TAXA
    CHECK (TAXA_ADMINISTRACAO >= 0);

ALTER TABLE FUNDO_INVESTIMENTO
    ADD CONSTRAINT CK_FUNDO_TIPO
    CHECK (TIPO_FUNDO IN ('RENDA_FIXA', 'MULTIMERCADO', 'ACOES'));

ALTER TABLE TRANSACAO
    ADD CONSTRAINT CK_TRANS_TIPO
    CHECK (TIPO IN ('COMPRA', 'VENDA'));

ALTER TABLE TRANSACAO
    ADD CONSTRAINT CK_TRANS_VALOR
    CHECK (VALOR >= 0);

ALTER TABLE RELATORIO
    ADD CONSTRAINT CK_REL_TIPO
    CHECK (TIPO IN ('ANUAL', 'MENSAL'));

ALTER TABLE CARTEIRA_ATIVO
    ADD CONSTRAINT CK_CART_ATIVO_QTD
    CHECK (QUANTIDADE > 0);

ALTER TABLE CARTEIRA_ATIVO
    ADD CONSTRAINT CK_CART_ATIVO_PRECO
    CHECK (PRECO_MEDIO >= 0);

