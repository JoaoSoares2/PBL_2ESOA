-- ============================================================
-- 3. CREATE TABLES
-- ============================================================

CREATE TABLE AUTENTICACAO_MULTIFATOR (
    ID          NUMBER(19)     NOT NULL,
    CODIGO      VARCHAR2(6),
    EXPIRACAO   TIMESTAMP
);

CREATE TABLE AUTENTICACAO (
    ID                        NUMBER(19)     NOT NULL,
    LOGIN                     VARCHAR2(255)  NOT NULL,
    SENHA                     VARCHAR2(255)  NOT NULL,
    ID_AUTENTICACAO_MFA       NUMBER(19)
);

CREATE TABLE PERFIL_INVESTIDOR (
    ID             NUMBER(19)     NOT NULL,
    NOME_PERFIL    VARCHAR2(50)   NOT NULL,
    DESCRICAO      VARCHAR2(500)  NOT NULL,
    NIVEL_RISCO    VARCHAR2(10)   NOT NULL
);

CREATE TABLE USUARIO (
    ID                       NUMBER(19)     NOT NULL,
    NOME                     VARCHAR2(150)  NOT NULL,
    EMAIL                    VARCHAR2(255)  NOT NULL,
    SENHA                    VARCHAR2(255)  NOT NULL,
    CPF                      VARCHAR2(14)   NOT NULL,
    TELEFONE                 VARCHAR2(20),
    ID_AUTENTICACAO          NUMBER(19),
    ID_PERFIL_INVESTIDOR     NUMBER(19)
);

CREATE TABLE EMPRESA (
    ID       NUMBER(19)     NOT NULL,
    NOME     VARCHAR2(150)  NOT NULL,
    CNPJ     VARCHAR2(18)   NOT NULL
);

CREATE TABLE CARTEIRA (
    ID             NUMBER(19)     NOT NULL,
    NOME           VARCHAR2(150)  NOT NULL,
    SALDO_TOTAL    NUMBER(18,2)   DEFAULT 0 NOT NULL,
    DATA_CRIACAO   TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ID_EMPRESA     NUMBER(19)     NOT NULL
);

CREATE TABLE ATIVO (
    ID             NUMBER(19)     NOT NULL,
    NOME           VARCHAR2(150)  NOT NULL,
    VALOR_ATUAL    NUMBER(18,4)   NOT NULL,
    QUANTIDADE     NUMBER(18,4)   NOT NULL
);

-- ACAO e FUNDO_INVESTIMENTO utilizam table-per-subclass:
-- o ID_ATIVO e simultaneamente PK da especializacao e FK de ATIVO.
CREATE TABLE ACAO (
    ID_ATIVO          NUMBER(19)     NOT NULL,
    TICKER            VARCHAR2(15)   NOT NULL,
    BOLSA             VARCHAR2(50)   NOT NULL,
    VARIACAO_DIARIA   NUMBER(9,4)    DEFAULT 0 NOT NULL
);

CREATE TABLE FUNDO_INVESTIMENTO (
    ID_ATIVO              NUMBER(19)    NOT NULL,
    TAXA_ADMINISTRACAO    NUMBER(9,4)   NOT NULL,
    TIPO_FUNDO            VARCHAR2(30)  NOT NULL
);

CREATE TABLE TRANSACAO (
    ID                NUMBER(19)     NOT NULL,
    TIPO              VARCHAR2(10)   NOT NULL,
    VALOR             NUMBER(18,2)   NOT NULL,
    DATA_TRANSACAO    TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DESCRICAO         VARCHAR2(500),
    ID_ATIVO          NUMBER(19),
    ID_CARTEIRA       NUMBER(19)     NOT NULL
);

CREATE TABLE RELATORIO (
    ID             NUMBER(19)    NOT NULL,
    TIPO           VARCHAR2(20)  NOT NULL,
    DATA_GERACAO   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONTEUDO       CLOB,
    ID_USUARIO     NUMBER(19)    NOT NULL
);

CREATE TABLE USUARIO_EMPRESA (
    ID             NUMBER(19)     NOT NULL,
    ID_USUARIO     NUMBER(19)     NOT NULL,
    ID_EMPRESA     NUMBER(19)     NOT NULL,
    CARGO          VARCHAR2(100)  NOT NULL,
    DATA_VINCULO   TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE CARTEIRA_ATIVO (
    ID             NUMBER(19)    NOT NULL,
    ID_CARTEIRA    NUMBER(19)    NOT NULL,
    ID_ATIVO       NUMBER(19)    NOT NULL,
    QUANTIDADE     NUMBER(18,4)  NOT NULL,
    PRECO_MEDIO    NUMBER(18,4)  NOT NULL
);

